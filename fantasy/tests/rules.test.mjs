// Firestore rules tests for the fantasy league (run inside `firebase emulators:exec`).
import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { doc, getDoc, setDoc, getDocs, collection, serverTimestamp, Timestamp } from 'firebase/firestore';
import fs from 'node:fs';
import assert from 'node:assert/strict';

const env = await initializeTestEnvironment({ projectId: 'demo-duf', firestore: { rules: fs.readFileSync(process.argv[2], 'utf8') } });
const user = (uid, email, verified = true) => env.authenticatedContext(uid, { email, email_verified: verified }).firestore();
const admin = user('adm', 'ZSteal94@gmail.com');
const ali = user('ali', 'ali@gmail.com');
const bob = user('bob', 'bob@gmail.com');
const eve = user('eve', 'eve@gmail.com');
const unverified = user('ali2', 'ali@gmail.com', false);
const H = 3600e3;
await env.withSecurityRulesDisabled(async (c) => {
  const db = c.firestore();
  await setDoc(doc(db, 'fantasyAccess/allowlist'), { emails: ['ali@gmail.com', 'bob@gmail.com'] });
  await setDoc(doc(db, 'fantasyGw/1'), { deadline: Timestamp.fromMillis(Date.now() - H), locked: false });
  await setDoc(doc(db, 'fantasyGw/2'), { deadline: Timestamp.fromMillis(Date.now() + H), locked: false });
  await setDoc(doc(db, 'fantasyGw/3'), { deadline: Timestamp.fromMillis(Date.now() + 48 * H), locked: true });
  await setDoc(doc(db, 'fantasyGw/1/entries/bob'), { uid: 'bob', squad: Array(9).fill('x'), sub: 'x', captain: 'x', vice: 'x', chip: null });
  await setDoc(doc(db, 'fantasyGw/2/entries/bob'), { uid: 'bob', squad: Array(9).fill('x'), sub: 'x', captain: 'x', vice: 'x', chip: null });
});
const entry = (uid, extra = {}) => ({ uid, squad: Array(9).fill('A'), sub: 'A', captain: 'A', vice: 'A', chip: null, savedAt: serverTimestamp(), ...extra });
let n = 0; const t = async (name, p) => { await p; n++; console.log('ok', name); };

await t('stranger: private league', assertFails(getDoc(doc(eve, 'fantasySettings/main'))));
await t('unverified email: refused', assertFails(getDoc(doc(unverified, 'fantasySettings/main'))));
await t('member reads settings', assertSucceeds(getDoc(doc(ali, 'fantasySettings/main'))));
await t('admin reads settings', assertSucceeds(getDoc(doc(admin, 'fantasySettings/main'))));
await t('member cannot read allowlist', assertFails(getDoc(doc(ali, 'fantasyAccess/allowlist'))));
await t('admin edits allowlist', assertSucceeds(setDoc(doc(admin, 'fantasyAccess/allowlist'), { emails: ['ali@gmail.com', 'bob@gmail.com'] })));
await t('member saves own team before deadline', assertSucceeds(setDoc(doc(ali, 'fantasyGw/2/entries/ali'), entry('ali'))));
await t('member cannot save after deadline (server time)', assertFails(setDoc(doc(ali, 'fantasyGw/1/entries/ali'), entry('ali'))));
await t('member cannot save in a locked week', assertFails(setDoc(doc(ali, 'fantasyGw/3/entries/ali'), entry('ali'))));
await t('member cannot save in a week that is not open', assertFails(setDoc(doc(ali, 'fantasyGw/9/entries/ali'), entry('ali'))));
await t('member cannot write someone else\'s team', assertFails(setDoc(doc(ali, 'fantasyGw/2/entries/bob'), entry('bob'))));
await t('client timestamp is refused', assertFails(setDoc(doc(ali, 'fantasyGw/2/entries/ali'), entry('ali', { savedAt: Timestamp.now() }))));
await t('extra fields refused', assertFails(setDoc(doc(ali, 'fantasyGw/2/entries/ali'), entry('ali', { points: 999 }))));
await t('8-man squad refused', assertFails(setDoc(doc(ali, 'fantasyGw/2/entries/ali'), entry('ali', { squad: Array(8).fill('A') }))));
await t('others\' teams hidden before the deadline (get)', assertFails(getDoc(doc(ali, 'fantasyGw/2/entries/bob'))));
await t('others\' teams hidden before the deadline (list)', assertFails(getDocs(collection(ali, 'fantasyGw/2/entries'))));
await t('own team readable before the deadline', assertSucceeds(getDoc(doc(ali, 'fantasyGw/2/entries/ali'))));
await t('everyone\'s teams visible after the deadline (get)', assertSucceeds(getDoc(doc(ali, 'fantasyGw/1/entries/bob'))));
await t('everyone\'s teams visible after the deadline (list)', assertSucceeds(getDocs(collection(ali, 'fantasyGw/1/entries'))));
await t('stranger cannot read teams after deadline', assertFails(getDocs(collection(eve, 'fantasyGw/1/entries'))));
await t('member cannot write match sheets', assertFails(setDoc(doc(ali, 'fantasySheets/w1-FAI-NAS'), { absent: [] })));
await t('member cannot write prices', assertFails(setDoc(doc(ali, 'fantasySettings/prices'), { updates: [] })));
await t('member cannot change the budget', assertFails(setDoc(doc(ali, 'fantasySettings/main'), { budgetHistory: [] })));
await t('member cannot move a deadline or unlock', assertFails(setDoc(doc(ali, 'fantasyGw/1'), { deadline: Timestamp.fromMillis(Date.now() + H), locked: false })));
await t('admin writes sheets', assertSucceeds(setDoc(doc(admin, 'fantasySheets/w1-FAI-NAS'), { absent: [] })));
await t('admin writes prices', assertSucceeds(setDoc(doc(admin, 'fantasySettings/prices'), { updates: [] })));
await t('admin sets deadlines', assertSucceeds(setDoc(doc(admin, 'fantasyGw/4'), { deadline: Timestamp.fromMillis(Date.now() + H), locked: false })));
await t('admin fixes a team after the deadline', assertSucceeds(setDoc(doc(admin, 'fantasyGw/1/entries/bob'), entry('bob'))));
await t('member creates own manager doc', assertSucceeds(setDoc(doc(ali, 'fantasyManagers/ali'), { uid: 'ali', email: 'ali@gmail.com', name: 'Ali', teamName: 'Ali FC', player: null, joined: 1 })));
await t('member cannot create someone else\'s manager doc', assertFails(setDoc(doc(ali, 'fantasyManagers/bob'), { uid: 'bob', email: 'ali@gmail.com', name: 'x', teamName: 'x', player: null, joined: 1 })));
await t('stranger cannot sign up as a manager', assertFails(setDoc(doc(eve, 'fantasyManagers/eve'), { uid: 'eve', email: 'eve@gmail.com', name: 'Eve', teamName: 'E', player: null, joined: 1 })));
await t('notes rules still work', assertSucceeds(setDoc(doc(eve, 'users/eve/notes/n1'), { text: 'hi', updated: 1 })));
await env.cleanup();
console.log(`\n${n} rules checks passed`);
